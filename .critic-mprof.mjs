import { chromium } from 'playwright';
import { listen } from './tools/serve.mjs';
const CHROME = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const { srv, port } = await listen(0);
const browser = await chromium.launch({ executablePath: CHROME, args: ['--use-angle=swiftshader','--use-gl=angle','--enable-unsafe-swiftshader','--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
const cdp = await page.context().newCDPSession(page);
await cdp.send('Profiler.enable');
await cdp.send('Profiler.setSamplingInterval', { interval: 2000 });
await cdp.send('Profiler.start');
await page.goto(`http://127.0.0.1:${port}/index.html?harness=1`, { waitUntil: 'commit', timeout: 30000 });
await page.waitForFunction(() => globalThis.__SB?.ready, null, { timeout: 200000 });
const { profile } = await cdp.send('Profiler.stop');
const byId = new Map(profile.nodes.map(n=>[n.id,n]));
const self = new Map();
const counts = new Map();
for (let i=0;i<profile.samples.length;i++) counts.set(profile.samples[i], (counts.get(profile.samples[i])||0)+1);
const total = profile.samples.length;
const dur = (profile.endTime - profile.startTime)/1000;
const rows = [...counts.entries()].map(([id,c])=>{ const n=byId.get(id); const f=n.callFrame; return { fn: f.functionName||'(anon)', url:(f.url||'').split('/').slice(-1)[0]+':'+(f.lineNumber+1), ms: Math.round(c/total*dur) }; }).sort((a,b)=>b.ms-a.ms).slice(0,20);
console.log('total ms', Math.round(dur));
console.table(rows);
await browser.close(); srv.close();
