const A = globalThis.__SB.app;
const M = A.moments;
const out = {};
out.ghostTex = M.ghost.frames[0].image.toDataURL().length;
out.ghostPos = M.ghost.mesh.position.toArray();
out.ghostVisible = M.ghost.mesh.visible;
const THREE = A.THREE;
const p = M.ghost.mesh.position.clone().project(A.camera);
out.ndc = [p.x.toFixed(3), p.y.toFixed(3), p.z.toFixed(3)];
const box = new THREE.Box3().setFromObject(M.ghost.mesh);
const top = new THREE.Vector3(box.min.x, box.max.y, box.min.z).project(A.camera);
const bot = new THREE.Vector3(box.min.x, box.min.y, box.min.z).project(A.camera);
out.px = Math.abs((top.y-bot.y)/2*900).toFixed(1);
out.framing = A.get('cameras').framing;
out.dataURLs = { ghost0: M.ghost.frames[0].image.toDataURL().slice(0,60) };
out.copVisible = M.cop.mesh.visible;
out.fired = M.fired;
out.faults = M.faults;
return out;
