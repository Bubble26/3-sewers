import { chromium } from 'playwright';
import { listen } from './tools/serve.mjs';
const CHROME = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const { srv, port } = await listen(0);
const browser = await chromium.launch({ executablePath: CHROME, args: ['--use-angle=swiftshader','--use-gl=angle','--enable-unsafe-swiftshader','--no-sandbox','--disable-dev-shm-usage','--hide-scrollbars'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1 });
page.on('pageerror', e => console.log(`[pageerror] ${e.message}`));
const t0 = Date.now();
await page.goto(`http://127.0.0.1:${port}/index.html?harness=1`, { waitUntil: 'commit', timeout: 20000 });
console.log('commit at ' + (Date.now()-t0));
await page.waitForFunction(() => globalThis.__SB && globalThis.__SB.ready, null, { timeout: 180000 });
console.log('READY at ' + (Date.now()-t0) + 'ms');
const marks = await page.evaluate(() => ({ marks: performance.getEntriesByType('mark').map(m=>[m.name, Math.round(m.startTime)]), nav: performance.getEntriesByType('navigation').map(n=>({dcl:Math.round(n.domContentLoadedEventEnd), load:Math.round(n.loadEventEnd)})) }));
console.log(JSON.stringify(marks));
const sc = await page.evaluate(() => globalThis.__SB.listScenarios());
console.log('SCENARIOS ' + JSON.stringify(sc));
await browser.close(); srv.close();
